"""Generate one shared compact catalogue; --check verifies committed output."""
import json,pathlib,sys
root=pathlib.Path(__file__).resolve().parents[1]
folder=root/'resources/locales'
catalogues={p.stem:json.loads(p.read_text(encoding='utf-8')) for p in folder.glob('*.json') if p.name!='source-inventory.json'}
assert set(catalogues['ru'])==set(catalogues['en'])
rows=[]
for lang,data in sorted(catalogues.items()):
 for key,value in sorted(data.items()):
  assert key in catalogues['en'] and isinstance(value,str) and '\0' not in value
  rows.append('  {'+', '.join(json.dumps(x,ensure_ascii=False) for x in (lang,key,value))+'},')
text='''// Generated by tools/generate-locales.py; edit resources/locales/*.json.
#include "cliptiq/locale.hpp"
#include <algorithm>
namespace cliptiq {
namespace {
struct Row {const char*language;const char*key;const char*value;};
const Row rows[]={
'''+ '\n'.join(rows)+'''
};
std::string chosen="en";
const char*find(std::string_view key){
 for(const auto&r:rows)if(chosen==r.language&&key==r.key)return r.value;
 for(const auto&r:rows)if(std::string_view(r.language)=="en"&&key==r.key)return r.value;
 return nullptr;
}
bool available(const std::string&s){for(const auto&r:rows)if(s==r.language)return true;return false;}
}
std::string activate_locale(std::string_view requested){
 std::string language(requested.substr(0,64));auto suffix=language.find_first_of(".@");if(suffix!=std::string::npos)language.resize(suffix);std::replace(language.begin(),language.end(),'_','-');
 if(!available(language)){auto dash=language.find('-');if(dash!=std::string::npos)language.resize(dash);}
 chosen=available(language)?language:"en";install_locale(chosen,find);return chosen;
}
}
'''
path=root/'core/src/locale_catalogue.cpp'
if '--check' in sys.argv:
 assert path.read_text(encoding='utf-8').replace('\r\n','\n')==text,'Run tools/generate-locales.py'
else:path.write_text(text,encoding='utf-8')
print('Locale schema:',len(catalogues['en']),'keys;',len(catalogues),'languages;',len(rows),'compiled rows')
